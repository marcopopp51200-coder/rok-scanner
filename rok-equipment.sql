-- ---------- Tabellen ----------
create table if not exists equipment_sets (
  id   text primary key,
  name text not null
);

create table if not exists equipment_set_effects (
  id          bigint generated always as identity primary key,
  set_id      text not null references equipment_sets(id) on delete cascade,
  pieces      smallint not null check (pieces between 2 and 6),
  stat        text not null,
  value       numeric(8,2) not null,
  description text
);

create table if not exists equipment (
  id              text primary key,
  name            text not null,
  slot            text not null,
  quality         text not null,
  set_id          text references equipment_sets(id),
  power           integer,
  gold_cost       bigint,
  commander_level smallint,
  iconic_group    text,
  image           text,
  notes           text,
  source          text
);
alter table equipment drop constraint if exists equipment_slot_check;
alter table equipment add  constraint equipment_slot_check
  check (slot in ('Weapon','Helmet','Chest','Gloves','Legs','Boots','Accessory'));
alter table equipment drop constraint if exists equipment_quality_check;
alter table equipment add  constraint equipment_quality_check
  check (quality in ('common','normal','advanced','elite','epic','legendary'));
alter table equipment add column if not exists game_id                 integer;
alter table equipment add column if not exists main_troop              text;
alter table equipment add column if not exists special_effect          text;
alter table equipment add column if not exists special_effect_refined  text;

create table if not exists equipment_stats (
  id            bigint generated always as identity primary key,
  equipment_id  text not null references equipment(id) on delete cascade,
  stat          text not null,
  value         numeric(8,2) not null
);
alter table equipment_stats add column if not exists refined_value numeric(8,2);
-- doppelte Werte (z. B. aus frueheren Importen) entfernen, damit der Unique-Index klappt
delete from equipment_stats a using equipment_stats b
  where a.id > b.id and a.equipment_id = b.equipment_id and a.stat = b.stat;
create unique index if not exists equipment_stats_uniq on equipment_stats (equipment_id, stat);

create table if not exists equipment_costs (
  equipment_id   text not null references equipment(id) on delete cascade,
  stage          text not null check (stage in ('craft','refine','awaken_1','awaken_2','awaken_3','awaken_4','awaken_5')),
  leather        integer not null default 0,
  iron           integer not null default 0,
  ebony          integer not null default 0,
  bone           integer not null default 0,
  blueprint      integer not null default 0,
  iconic_crystal integer not null default 0,
  gold           bigint  not null default 0,
  primary key (equipment_id, stage)
);

-- Iconic-Stufen I-V; equipment_key = Teil-ID oder 'default-accessory'
create table if not exists equipment_iconic (
  equipment_key text not null,
  tier          smallint not null check (tier between 1 and 5),
  type          text not null,          -- base_stat | percent_stat | flat_stat | special
  stat          text,
  value         numeric(10,2),
  crit_value    numeric(10,2),
  season_values jsonb,                  -- base_stat: {"kvk1_2":1,"kvk3":2,"soc":3}
  special_name  text,
  description   text,
  special_values jsonb,
  special_crit   jsonb,
  primary key (equipment_key, tier)
);

-- ---------- Lesen fuer alle ----------
do $$
declare t text;
begin
  foreach t in array array['equipment_sets','equipment_set_effects','equipment','equipment_stats','equipment_costs','equipment_iconic'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "read all" on %I', t);
    execute format('create policy "read all" on %I for select using (true)', t);
  end loop;
end $$;

